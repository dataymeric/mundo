"""Conditioning context of the backbones.

Two sources: the observations of neighboring windows and, optionally, the previous
window as generated by the model. `pack_surface` stacks them in one channel order,
the same for training and evaluation.
"""

import torch

from mundo.operator import Operator, coarsen


def fmap(flag: torch.Tensor, spatial) -> torch.Tensor:
    """Broadcast one scalar per sample over space: (B,) -> (B, 1, *S)."""
    return flag.view(-1, 1, *([1] * len(spatial))).expand(-1, 1, *spatial)


def observed(op: Operator, before, after, flags):
    """Observations of the neighboring windows, as channels.

    Args:
        op: Window operator.
        before: (B, n_before, Lf, C, *S) preceding windows.
        after: (B, n_after, Lf, C, *S) following windows.
        flags: (B, n_before + n_after) presence of each neighbor.

    Returns:
        ctx: (B, k * n * C, *S), n the observed frames per window.
        flags: `flags`, unchanged.
    """
    wins = torch.cat([before, after], dim=1)
    B, k = wins.shape[:2]
    y = op.apply(wins.flatten(0, 1)).reshape(B, k, -1, *wins.shape[3:])
    return y.flatten(1, 3), flags


def generated(ops: list[Operator], prev_fine: torch.Tensor) -> torch.Tensor:
    """The previous window as context, one frame per level of the recursion.

    Args:
        ops: The R per-level operators, coarse to fine.
        prev_fine: (B, Lf, C, *S) previous window.

    Returns:
        (B, R * C, *S) last frame of `prev_fine` at each level's resolution, coarse to
        fine.
    """
    return torch.cat(
        [coarsen(prev_fine, ops[r + 1 :])[:, -1] for r in range(len(ops))], dim=1
    )


def drop_groups(x: torch.Tensor, flags: torch.Tensor, p: float, g):
    """Context dropout: hide each context group with probability `p`.

    Teaches the model to work when a neighbor is missing, as at trajectory edges.

    Args:
        x: (B, k, ...) context, one group per neighbor.
        flags: (B, k) presence of each group.
        p: Drop probability.
        g: Torch generator.

    Returns:
        `x` and `flags`, with the dropped groups set to 0.
    """
    keep = (torch.rand(flags.shape, device=x.device, generator=g) >= p).float() * flags
    return x * keep.view(*keep.shape, *([1] * (x.dim() - 2))), keep


def pack_surface(obs, statics, obs_ctx, obs_flags, gen_ctx=None, gen_flag=None):
    """Concatenate all context channels.

    Args:
        obs: (B, n * C, *S) the window's own observation, or `None`.
        statics: (Cs, *S) static maps, or `None`.
        obs_ctx: (B, k * n * C, *S) from `observed`.
        obs_flags: (B, k) neighbor presence.
        gen_ctx: (B, R * C, *S) from `generated`, or `None`.
        gen_flag: (B,) presence of the previous window.

    Returns:
        (B, c_surface, *S).
    """
    B, spatial = obs_ctx.shape[0], obs_ctx.shape[2:]
    parts = [] if obs is None else [obs]
    if statics is not None:
        parts.append(statics.to(obs_ctx)[None].expand(B, -1, *spatial))
    parts += [obs_ctx] + [
        fmap(obs_flags[:, j], spatial) for j in range(obs_flags.shape[1])
    ]
    if gen_ctx is not None:
        parts += [gen_ctx, fmap(gen_flag, spatial)]
    return torch.cat(parts, dim=1)


def c_surface(
    C, n_obs, k_neighbors, c_statics, n_levels, generated: bool, own: bool = False
) -> int:
    """Number of channels returned by `pack_surface`."""
    return (
        (n_obs * C if own else 0)
        + c_statics
        + k_neighbors * n_obs * C
        + k_neighbors
        + (n_levels * C + 1 if generated else 0)
    )
